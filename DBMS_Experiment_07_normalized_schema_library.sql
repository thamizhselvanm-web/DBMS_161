-- ============================================================================
-- 5. RELATIONAL INTEGRITY & MULTI-TABLE JOIN VERIFICATION
-- ============================================================================

-- 5.1 Query Books along with Author details (Resolving M:N Junction)
SELECT
    b.BookID,
    b.Title,
    b.Genre,
    a.FirstName || ' ' || a.LastName AS AuthorName
FROM Books b
JOIN BookAuthors ba ON b.BookID = ba.BookID
JOIN Authors a ON ba.AuthorID = a.AuthorID
ORDER BY b.BookID;

/* OUTPUT:
BOOKID | TITLE                                | GENRE     | AUTHORNAME
-------+--------------------------------------+-----------+--------------
1      | 1984                                 | Dystopian | George Orwell
2      | Brave New World                      | Dystopian | Aldous Huxley
3      | Harry Potter and the Sorcerer's Stone | Fantasy   | J.K. Rowling
3 rows selected.
*/

-- 5.2 Query Active Borrowings with Borrower and Book Details
SELECT
    br.BorrowerID,
    br.FirstName || ' ' || br.LastName AS BorrowerName,
    bk.Title,
    bb.BorrowedDate,
    bb.ReturnDate
FROM BorrowedBooks bb
JOIN Borrowers br ON bb.BorrowerID = br.BorrowerID
JOIN Books bk ON bb.BookID = bk.BookID
ORDER BY br.BorrowerID;

/* OUTPUT:
BORROWERID | BORROWERNAME | TITLE                                | BORROWEDDATE | RETURNDATE
-----------+--------------+--------------------------------------+--------------+-----------
1          | John Doe     | 1984                                 | 01-MAR-23    | 15-MAR-23
