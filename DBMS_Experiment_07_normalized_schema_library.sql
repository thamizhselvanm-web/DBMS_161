-- ============================================================================
-- 2. CREATE NORMALIZED TABLES
-- ============================================================================

CREATE TABLE Authors (
    AuthorID  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FirstName VARCHAR2(50) NOT NULL,
    LastName  VARCHAR2(50) NOT NULL
);

CREATE TABLE Books (
    BookID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Title           VARCHAR2(100) NOT NULL,
    Genre           VARCHAR2(50),
    PublicationYear NUMBER(4)
);

CREATE TABLE BookAuthors (
    BookID   NUMBER,
    AuthorID NUMBER,
    PRIMARY KEY (BookID, AuthorID),
    CONSTRAINT fk_ba_book   FOREIGN KEY (BookID)   REFERENCES Books(BookID),
    CONSTRAINT fk_ba_author FOREIGN KEY (AuthorID) REFERENCES Authors(AuthorID)
);

CREATE TABLE Borrowers (
    BorrowerID     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FirstName      VARCHAR2(50) NOT NULL,
    LastName       VARCHAR2(50) NOT NULL,
    MembershipDate DATE DEFAULT SYSDATE
);

CREATE TABLE BorrowedBooks (
    BorrowerID   NUMBER,
    BookID       NUMBER,
    BorrowedDate DATE NOT NULL,
    ReturnDate   DATE,
    PRIMARY KEY (BorrowerID, BookID, BorrowedDate),
    CONSTRAINT fk_bb_borrower FOREIGN KEY (BorrowerID) REFERENCES Borrowers(BorrowerID),
    CONSTRAINT fk_bb_book     FOREIGN KEY (BookID)     REFERENCES Books(BookID)
);

